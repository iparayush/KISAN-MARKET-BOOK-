const mongoose = require('mongoose');

const notificationSchema = new mongoose.Schema(
  {
    recipientId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: true,
      index: true,
    },
    title: {
      type: String,
      required: true,
    },
    message: {
      type: String,
      required: true,
    },
    type: {
      type: String,
      enum: ['QUEUE', 'PROCUREMENT', 'PAYMENT', 'ALERT'],
      default: 'QUEUE',
    },
    channel: {
      type: String,
      enum: ['IN_APP', 'SMS', 'IVR', 'PUSH'],
      default: 'IN_APP',
    },
    isRead: {
      type: Boolean,
      default: false,
    },
  },
  {
    timestamps: true,
  }
);

module.exports = mongoose.model('Notification', notificationSchema);
